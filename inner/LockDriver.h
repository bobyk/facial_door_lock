#pragma once
#include <Arduino.h>

// Керування мотором замка через 2-канальний H-міст (IN1/IN2). Імпульсне
// керування - мотор не тримає напругу постійно.
// !!! Апаратна вимога (не вирішується в коді): мотор - індуктивне навантаження
// (зворотний ЕРС) в тому ж корпусі, що й MCU. На платі обов'язкова гальванічна
// розв'язка (оптрон) і снаббер/діод на обмотці мотора.
// pulse()/open()/close() - свідомо коротка блокуюча ділянка (типово ~500мс) - єдиний
// намірений виняток з вимоги "неблокуючий FSM", як і задокументовано в ТЗ.
class LockDriver {
public:
    LockDriver(uint8_t in1Pin, uint8_t in2Pin, uint16_t pulseMs = 500)
        : _in1(in1Pin), _in2(in2Pin), _pulseMs(pulseMs) {}

    void begin();
    void open();  // блокуючий імпульс на _pulseMs
    void close();
    void stop();

private:
    uint8_t _in1, _in2;
    uint16_t _pulseMs;
};
